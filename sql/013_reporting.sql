CREATE TABLE IF NOT EXISTS loyalty.campaign_comparison_results (
    comparison_scope TEXT NOT NULL CHECK (comparison_scope IN ('overall', 'exploratory')),
    pair_number INTEGER NOT NULL CHECK (pair_number > 0),
    rfm_segment TEXT NOT NULL,
    offer_a TEXT NOT NULL REFERENCES loyalty.offers (offer_id),
    offer_b TEXT NOT NULL REFERENCES loyalty.offers (offer_id),
    deliveries_a INTEGER NOT NULL,
    deliveries_b INTEGER NOT NULL,
    completed_a INTEGER NOT NULL,
    completed_b INTEGER NOT NULL,
    rate_a_pct DOUBLE PRECISION,
    rate_b_pct DOUBLE PRECISION,
    difference_pp DOUBLE PRECISION,
    ci95_low_pp DOUBLE PRECISION,
    ci95_high_pp DOUBLE PRECISION,
    p_value DOUBLE PRECISION,
    p_holm DOUBLE PRECISION,
    reject_holm_05 BOOLEAN NOT NULL,
    customer_clusters INTEGER NOT NULL,
    common_waves INTEGER[] NOT NULL,
    status TEXT NOT NULL,
    source_manifests JSONB NOT NULL,
    PRIMARY KEY (comparison_scope, pair_number, rfm_segment)
);
